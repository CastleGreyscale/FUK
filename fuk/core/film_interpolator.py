# core/film_interpolator.py
"""
FILM Frame Interpolator for FUK Pipeline

Google's FILM (Frame Interpolation for Large Motion) via the PyTorch port.
Replaces RIFE with in-process PyTorch inference — no external binaries.

Model: dajes/frame-interpolation-pytorch (Apache 2.0)
Paper: Reda et al., FILM: Frame Interpolation for Large Motion, ECCV 2022

Precision, and why it is not what it looks like
    The model itself takes arbitrary float tensors — interpolate_pair accepts
    whatever you hand it. Everything limiting this to 8-bit is in *our* wrapper,
    not the model and not a vendored engine:

      _load_frame   reads 8- or 16-bit via IMREAD_UNCHANGED, scales by dtype
      _save_frame   clamps to [0,1] and writes 8- or 16-bit PNG
      precision     float32 by default, on CPU and CUDA alike

    Clamping happens only at the PNG writer, so interpolate_frames itself
    carries whatever range the model produced. Feeding it linear-light float is
    therefore a matter of skipping the PNG stage entirely — no patch against
    anyone else's repo, unlike seedvr2_backend where the 8-bit round trip is
    baked into a vendored engine. The remaining question is behavioural: FILM
    was trained on display-referred images, so linear light is out of
    distribution, and that is untested here.

Why this is not in the latent -> EXR path
    Bit depth is the smaller problem. Interpolation *changes the frame count*,
    and in a VFX sequence the beauty EXR has to stay in lockstep with its AOVs.

    Cryptomattes cannot be interpolated at all — they are object ID maps, and a
    blend of two IDs is not a third object. Depth blends across occlusion edges
    and normals need renormalising, so neither survives naive interpolation
    either.

    The fix is ordering, not precision: interpolate the beauty first, then
    generate depth/normals/crypto from the interpolated sequence, so every layer
    derives from the same frames and crypto is regenerated by SAM2 on real
    images rather than blended. Interpolating after AOV generation desynchronises
    the sequence and silently corrupts the mattes.

    There is no latent-space shortcut here either, for a different reason than
    SeedVR2: Wan's VAE is 4x temporally compressed, so latent frames are not
    video frames and interpolating them interpolates groups of four.

Usage:
    interpolator = FILMInterpolator()
    result = interpolator.interpolate_video(
        input_path, output_path,
        source_fps=16, target_fps=24,
    )
"""

